    #[test]
    fn builtins_give_what_python_gives() {
        let mut off = Vec::new();
        for (f, args, want) in cases() {
            let want = want.map_err(|(c, m)| Raised { class: c.into(), message: m.into() });
            let got = call_pure(f, &args);
            if got != want { off.push(format!("{f}{args:?}\n  got  {got:?}\n  want {want:?}")); }
        }
        assert!(off.is_empty(), "{}", off.join("\n"));
    }
